from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "generated"

all_df = pd.read_csv(DATA / "synthetic_all_records.csv")
train = pd.read_csv(DATA / "train.csv")
test = pd.read_csv(DATA / "test.csv")

print("=" * 60)
print("SYNTHETIC FOOD SAFETY DATASET AUDIT")
print("=" * 60)

# 1. Dimensions and schema
print("\n[1] DATASET DIMENSIONS")
print("All:", all_df.shape)
print("Train:", train.shape)
print("Test:", test.shape)
print("Columns:", ", ".join(all_df.columns))

# 2. Missing values
print("\n[2] MISSING VALUES")
missing = all_df.isna().sum()
print(missing[missing > 0].to_string() if missing.any() else "None found")

# 3. Duplicate rows and identifiers
print("\n[3] DUPLICATE CHECKS")
print("Duplicate full rows:", int(all_df.duplicated().sum()))
print("Duplicate record IDs:", int(all_df["record_id"].duplicated().sum()))

# 4. Risk label distribution
print("\n[4] RISK LABEL DISTRIBUTION")
counts = all_df["risk_level"].value_counts()
print(counts.to_string())
print("\nPercentages:")
print((all_df["risk_level"].value_counts(normalize=True) * 100).round(2).to_string())

# 5. Train/test separation
print("\n[5] TRAIN/TEST SEPARATION")
train_ids = set(train["record_id"])
test_ids = set(test["record_id"])
print("Overlapping IDs:", len(train_ids & test_ids))
print("Train IDs missing from full dataset:", len(train_ids - set(all_df["record_id"])))
print("Test IDs missing from full dataset:", len(test_ids - set(all_df["record_id"])))

# 6. Risk distribution by district
print("\n[6] DISTRICT AND RISK COUNTS")
district_risk = pd.crosstab(all_df["district"], all_df["risk_level"])
print(district_risk.to_string())
district_risk.to_csv(DATA / "district_risk_counts.csv")

# 7. Inspect numeric inputs by label
print("\n[7] NUMERIC FEATURE MEANS BY RISK")
numeric = [
    "hygiene_score",
    "temperature_control_deviation",
    "unsafe_water_indicator",
    "pest_signs",
    "cross_contamination_indicator",
    "expired_food_indicator",
    "complaints_30d",
    "illness_reports_7d",
    "days_since_last_inspection",
]
print(all_df.groupby("risk_level")[numeric].mean().round(3).to_string())

# 8. Label provenance warning
print("\n[8] INTERPRETATION")
print("Labels are generated by illustrative rules, not verified outcomes.")
print("High model accuracy against these labels would not prove real-world")
print("food-safety prediction accuracy.")
print("Exclude record_id from model features.")
print("Do not use risk_level to create model input features.")

# 9. Save audit summary
summary = {
    "total_records": len(all_df),
    "train_records": len(train),
    "test_records": len(test),
    "missing_cells": int(all_df.isna().sum().sum()),
    "duplicate_rows": int(all_df.duplicated().sum()),
    "duplicate_ids": int(all_df["record_id"].duplicated().sum()),
    "train_test_id_overlap": len(train_ids & test_ids),
    "risk_counts": {str(k): int(v) for k, v in counts.items()},
}

import json
(DATA / "audit_summary.json").write_text(
    json.dumps(summary, indent=2), encoding="utf-8"
)
print("\nAudit summary saved to data/generated/audit_summary.json")
